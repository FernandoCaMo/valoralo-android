package com.valoralo.data.auth

import android.annotation.SuppressLint
import android.content.Context
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential

/**
 * "Sign in with Google" through Credential Manager. Needs an Activity context.
 *
 * The web client id (default_web_client_id) is generated by the Google Services plugin
 * from google-services.json once the Google provider is enabled in Firebase. It is read
 * at runtime so the app still builds without it.
 */
object GoogleSignIn {

    @SuppressLint("DiscouragedApi")
    private fun webClientId(context: Context): String? {
        val id = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
        return if (id == 0) null else context.getString(id)
    }

    fun disponible(context: Context): Boolean = webClientId(context) != null

    /** Returns a Google ID token for Firebase, or throws [ErrorCuenta]. */
    suspend fun obtenerIdToken(context: Context): String {
        val clientId = webClientId(context) ?: throw ErrorCuenta(TipoErrorCuenta.GOOGLE_NO_CONFIGURADO)
        val peticion = GetCredentialRequest.Builder()
            .addCredentialOption(GetSignInWithGoogleOption.Builder(clientId).build())
            .build()
        val resultado = try {
            CredentialManager.create(context).getCredential(context, peticion)
        } catch (e: GetCredentialCancellationException) {
            throw ErrorCuenta(TipoErrorCuenta.GOOGLE_CANCELADO, e)
        } catch (e: GetCredentialException) {
            throw ErrorCuenta(TipoErrorCuenta.DESCONOCIDO, e)
        }
        val credencial = resultado.credential
        if (credencial is CustomCredential && credencial.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
            return GoogleIdTokenCredential.createFrom(credencial.data).idToken
        }
        throw ErrorCuenta(TipoErrorCuenta.DESCONOCIDO)
    }

    /** Forget the chosen Google account on sign-out. */
    suspend fun olvidar(context: Context) {
        runCatching { CredentialManager.create(context).clearCredentialState(ClearCredentialStateRequest()) }
    }
}
